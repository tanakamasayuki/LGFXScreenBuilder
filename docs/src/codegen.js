// Code generation: project model -> "<Project>.h" (the §11 facade + the
// lgfxsb::Project descriptor consumed by the shared engine). Pure module (no
// DOM), so it also runs under Node for round-trip tests.
//
// Output shape matches examples/Basic/MyScreen.h. Generated-code comments are
// English-only per SPEC §10/§13.
import { sceneById, placement, DATUMS } from './model.js';

const PART_ENUM = { Group: 'Group', Rect: 'Rect', Text: 'Text', Image: 'Image' };
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const hex = (css) => '0x' + (css || '#000000').replace('#', '').padStart(6, '0').toLowerCase();
const cstr = (s) => '"' + String(s == null ? '' : s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

// Flatten all scenes' parts into one indexed list (matches descriptor layout).
function flatten(project) {
  const flat = []; // { sceneId, part, gi }
  const sceneRange = {}; // sceneId -> {start,count}
  for (const sc of project.scenes) {
    const start = flat.length;
    for (const p of sc.parts) flat.push({ sceneId: sc.id, part: p, gi: flat.length });
    sceneRange[sc.id] = { start, count: sc.parts.length };
  }
  // resolve parent (part id within the same scene) to a global index, else -1
  const giOf = (sceneId, partId) => flat.find((f) => f.sceneId === sceneId && f.part.id === partId)?.gi ?? -1;
  for (const f of flat) f.parentGi = f.part.parent ? giOf(f.sceneId, f.part.parent) : -1;
  return { flat, sceneRange };
}

// Access path of a part from its scene struct root, via group ancestors.
function pathOf(scene, part) {
  const segs = [part.id];
  let cur = part;
  while (cur.parent) {
    const parent = scene.parts.find((p) => p.id === cur.parent);
    if (!parent) break;
    segs.unshift(parent.id);
    cur = parent;
  }
  return segs.join('.');
}

// Build the typed scene struct body (nested by Group; Text -> const char* field).
function structBody(project, scene, parentId, indent) {
  const pad = '  '.repeat(indent);
  let out = '';
  for (const p of scene.parts) {
    if ((p.parent || null) !== (parentId || null)) continue;
    if (p.type === 'Group') {
      out += `${pad}struct ${cap(p.id)} {\n`;
      out += structBody(project, scene, p.id, indent + 1);
      out += `${pad}} ${p.id};\n`;
    } else if (p.type === 'Text') {
      const lo = placement(project.profiles.find((pr) => pr.id === project.defaultProfile) || project.profiles[0], scene.id, p.id);
      out += `${pad}const char* ${p.id} = ${cstr(lo ? lo.text : '')};\n`;
    }
  }
  return out;
}

export function generateHeader(project) {
  const name = project.name;
  const { flat, sceneRange } = flatten(project);
  const defProfile = project.profiles.find((p) => p.id === project.defaultProfile) || project.profiles[0];
  const defIndex = Math.max(0, project.profiles.indexOf(defProfile));

  let s = '';
  s += `#pragma once\n\n`;
  s += `// Generated by LGFXScreenBuilder. Do not edit by hand.\n`;
  s += `// Include <LovyanGFX.hpp> (or M5GFX) and <LGFXScreenBuilder.h> before this header.\n\n`;
  s += `namespace ${name} {\n\n`;

  // Profile enum
  s += `enum class Profile : uint8_t { Auto = 0, ${project.profiles.map((p) => p.id).join(', ')} };\n\n`;

  // Scene structs
  s += `namespace Scene {\n`;
  project.scenes.forEach((sc, i) => {
    s += `  struct ${sc.id} {\n    static constexpr lgfxsb::SceneId id = ${i};\n`;
    s += structBody(project, sc, null, 2);
    s += `  };\n`;
  });
  s += `}\n\n`;

  // detail: parts / scenes / layouts / profiles
  s += `namespace detail {\n\n`;
  s += `static const lgfxsb::PartDesc kParts[] = {\n`;
  flat.forEach((f) => {
    const p = f.part;
    const text = p.type === 'Text'
      ? cstr((placement(defProfile, f.sceneId, p.id) || {}).text || '')
      : 'nullptr';
    s += `  {${cstr(p.id)}, lgfxsb::PartType::${PART_ENUM[p.type]}, ${f.parentGi}, ${text}, -1},  // ${f.gi} ${f.sceneId}.${p.id}\n`;
  });
  s += `};\nstatic constexpr uint16_t kPartCount = ${flat.length};\n\n`;

  s += `static const lgfxsb::SceneDesc kScenes[] = {\n`;
  project.scenes.forEach((sc, i) => {
    const r = sceneRange[sc.id];
    s += `  {${i}, ${cstr(sc.id)}, ${r.start}, ${r.count}},\n`;
  });
  s += `};\n\n`;

  // layouts [profile][part]
  s += `// {x, y, w, h, datum, size, color, visible}\n`;
  s += `static const lgfxsb::PartLayout kLayouts[] = {\n`;
  project.profiles.forEach((pr) => {
    s += `  // ---- Profile: ${pr.id} ${pr.w}x${pr.h} rot${pr.rotation} ----\n`;
    flat.forEach((f) => {
      const e = placement(pr, f.sceneId, f.part.id) || {};
      const isText = f.part.type === 'Text';
      const x = e.x || 0, y = e.y || 0;
      const w = isText ? 0 : (e.w || 0), h = isText ? 0 : (e.h || 0);
      const datum = isText ? `(uint8_t)lgfxsb::Datum::${e.datum || 'TL'}` : '0';
      const size = isText ? (e.size || 1) : 0;
      const color = (f.part.type === 'Rect') ? hex(e.color) : (isText ? hex(e.color) : '0');
      const vis = (e.visible === false) ? 'false' : 'true';
      s += `  {${x}, ${y}, ${w}, ${h}, ${datum}, ${fmtFloat(size)}, ${color}, ${vis}},  // ${f.sceneId}.${f.part.id}\n`;
    });
  });
  s += `};\n\n`;

  s += `static const lgfxsb::ProfileDesc kProfiles[] = {\n`;
  project.profiles.forEach((pr) => {
    // boards[] auto-detect table is emitted empty for now (runtime falls back to default).
    s += `  {${pr.w}, ${pr.h}, ${pr.rotation}, nullptr, 0},\n`;
  });
  s += `};\n\n} // namespace detail\n\n`;

  // Project descriptor
  s += `static const lgfxsb::Project project = {\n`;
  s += `  detail::kProfiles, ${project.profiles.length}, /*defaultProfile*/ ${defIndex},\n`;
  s += `  detail::kScenes, ${project.scenes.length},\n`;
  s += `  detail::kParts, detail::kPartCount,\n`;
  s += `  detail::kLayouts,\n`;
  s += `  /*background*/ ${hex(project.background)},\n};\n\n`;

  // Facade
  s += `class Screen : public lgfxsb::Renderer {\n public:\n`;
  s += `  explicit Screen(lgfx::LGFX_Device& gfx) : lgfxsb::Renderer(gfx, project) {}\n`;
  s += `  void setProfile(Profile p) { _profile = static_cast<uint8_t>(p); }\n`;
  project.scenes.forEach((sc) => {
    const texts = sc.parts.map((p, k) => ({ p, k })).filter((x) => x.p.type === 'Text');
    if (texts.length === 0) {
      s += `  void show(const Scene::${sc.id}&) { renderScene(Scene::${sc.id}::id, nullptr, 0); }\n`;
    } else {
      s += `  void show(const Scene::${sc.id}& s) {\n    lgfxsb::Value v[${sc.parts.length}];\n`;
      texts.forEach(({ p, k }) => {
        s += `    v[${k}] = lgfxsb::Value::text(s.${pathOf(sc, p)});\n`;
      });
      s += `    renderScene(Scene::${sc.id}::id, v, ${sc.parts.length});\n  }\n`;
    }
    s += `  void update(const Scene::${sc.id}& s) { show(s); }\n`;
  });
  s += `};\n\n`;

  s += `} // namespace ${name}\n`;
  return s;
}

function fmtFloat(n) {
  const v = Number(n);
  return Number.isInteger(v) ? v.toFixed(1) + 'f' : v + 'f';
}
