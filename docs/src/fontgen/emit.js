// C header emitter for generated embedded fonts (§8.7.7).
//
// The output is a self-contained header holding the U8g2 byte array plus the
// `lgfx::U8g2font` object that wraps it, so using it on the device is:
//
//     #include "MyFont.h"
//     display.setFont(&MyFont);
//
// The array is `const` (not PROGMEM-only) because on ESP32 `const` already
// lives in flash and is directly addressable; the PROGMEM attribute is applied
// through a guard so the same header still builds on AVR-style targets.
//
// Every header carries its attribution block. That is not decoration: OFL-1.1
// and Apache-2.0 both require the notice to travel with derived font data, and
// the generated array IS derived font data.

const HEX = (b) => '0x' + b.toString(16).padStart(2, '0');

// C identifier from a user-supplied name (leading digit gets a prefix).
export function sanitizeIdent(name) {
  const s = String(name || '').replace(/[^A-Za-z0-9_]/g, '_');
  return /^[A-Za-z_]/.test(s) ? s : 'font_' + s;
}

// Wrap a codepoint list as compact "U+0020-U+007E, U+00B0" text for the notice.
function summarizeRanges(cps, limit = 24) {
  if (!cps.length) return '(none)';
  const parts = [];
  let start = cps[0], prev = cps[0];
  const push = () => parts.push(start === prev
    ? `U+${start.toString(16).toUpperCase().padStart(4, '0')}`
    : `U+${start.toString(16).toUpperCase().padStart(4, '0')}-${prev.toString(16).toUpperCase().padStart(4, '0')}`);
  for (const c of cps.slice(1)) {
    if (c === prev + 1) { prev = c; continue; }
    push();
    start = prev = c;
  }
  push();
  if (parts.length <= limit) return parts.join(', ');
  return parts.slice(0, limit).join(', ') + `, … (+${parts.length - limit} more ranges)`;
}

/**
 * Render the attribution / provenance comment that heads every generated file.
 * Kept separate so the same text can be shown in the UI before downloading.
 */
export function licenseNotice({ name, source = {}, sources = null, charset = {}, stats = {} }) {
  // A font can be composed from several typefaces (§8.7.7 fallback), and it is
  // then a derived work of every one of them — so each gets a full entry.
  const list = sources && sources.length ? sources : [source];
  const L = [];
  L.push(`${name} — embedded bitmap font for LovyanGFX / M5GFX`);
  L.push('');
  L.push('Generated by LGFXScreenBuilder Font Generator');
  L.push('https://tanakamasayuki.github.io/LGFXFontToolJs/generator.html');
  L.push('');
  list.forEach((src, i) => {
    const head = i === 0 ? 'Font source' : `Font source ${i + 1} (filled in ${src.count} characters)`;
    L.push(`--- ${head} ${'-'.repeat(Math.max(3, 62 - head.length))}`);
    L.push(`Typeface : ${src.family || '(unknown)'}`);
    if (src.by) L.push(`Author   : ${src.by}`);
    if (src.license) {
      L.push(`License  : ${src.license.name || src.license.id}`);
      if (src.license.url) L.push(`           ${src.license.url}`);
    } else {
      L.push('License  : UNKNOWN — supplied as a local file.');
      L.push('           You are responsible for confirming that this typeface may be');
      L.push('           embedded and redistributed in compiled firmware.');
    }
    if (src.origin) L.push(`Obtained : ${src.origin}`);
    if (src.chars) L.push(`Supplied : ${src.chars.slice(0, 60)}`);
    L.push('');
  });
  L.push(`This file contains glyph outlines rasterized from the ${list.length > 1 ? 'typefaces' : 'typeface'} above`);
  L.push(`and is a derived work of ${list.length > 1 ? 'each of them' : 'it'}. Keep this notice with the file and`);
  L.push('with any binary built from it.');
  L.push('');
  L.push('--- Generation ----------------------------------------------------');
  L.push(`Format   : u8g2 (1bpp) — lgfx::U8g2font`);
  L.push(`Size     : ${stats.height}px line height (ascent ${stats.ascent}, descent ${stats.descent})`);
  L.push(`Glyphs   : ${stats.glyphCount}`);
  L.push(`Data     : ${stats.bytes} bytes`);
  if (charset.presets?.length) L.push(`Presets  : ${charset.presets.join(', ')}`);
  L.push(`Coverage : ${summarizeRanges(charset.codepoints || [])}`);
  return L.join('\n');
}

/**
 * Emit the full `.h` file.
 *
 * @param {Object} opts
 *   name       - C identifier for the font object
 *   data       - Uint8Array from encodeU8g2()
 *   source     - { family, by, license, origin } (the primary typeface)
 *   sources    - every typeface used, primary first (§8.7.7 fallback)
 *   charset    - { presets, codepoints }
 *   stats      - { height, ascent, descent, glyphCount, bytes }
 */
export function emitHeader({ name, data, source, sources, charset, stats }) {
  const ident = sanitizeIdent(name);
  const guard = `LGFXSB_FONT_${ident.toUpperCase()}_H`;

  let s = '';
  s += '// ' + licenseNotice({ name: ident, source, sources, charset, stats }).split('\n').join('\n// ') + '\n';
  s += '\n';
  s += `#ifndef ${guard}\n#define ${guard}\n\n`;
  s += '#include <stdint.h>\n\n';
  s += '// LovyanGFX (or M5GFX / M5Unified, which re-export the same types) must be\n';
  s += '// included before this header so lgfx::U8g2font is visible.\n';
  s += '#if !defined(LGFX_USE_V1) && !defined(__LOVYANGFX_HPP__) && !defined(_M5GFX_H_)\n';
  s += '  #include <LovyanGFX.hpp>\n';
  s += '#endif\n\n';
  s += '#ifndef LGFXSB_FONT_PROGMEM\n';
  s += '  #if defined(PROGMEM)\n';
  s += '    #define LGFXSB_FONT_PROGMEM PROGMEM\n';
  s += '  #else\n';
  s += '    #define LGFXSB_FONT_PROGMEM\n';
  s += '  #endif\n';
  s += '#endif\n\n';

  s += `static const uint8_t ${ident}_data[${data.length}] LGFXSB_FONT_PROGMEM = {\n`;
  const PER_LINE = 16;
  for (let i = 0; i < data.length; i += PER_LINE) {
    s += '  ' + Array.from(data.slice(i, i + PER_LINE), HEX).join(', ') + (i + PER_LINE < data.length ? ',' : '') + '\n';
  }
  s += '};\n\n';
  s += `// Usage:  display.setFont(&${ident});\n`;
  s += `static const lgfx::U8g2font ${ident}(${ident}_data);\n\n`;
  s += `#endif // ${guard}\n`;
  return s;
}
