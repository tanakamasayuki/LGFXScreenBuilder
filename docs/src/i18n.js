export const LANGS = ['en', 'ja', 'zh-Hans', 'zh-Hant', 'ko', 'es', 'fr', 'de'];
let lang = 'en';

export function detectLanguage() {
  const l = (globalThis.navigator && globalThis.navigator.language || 'en').toLowerCase();
  if (l.startsWith('ja')) return 'ja';
  if (l.startsWith('zh')) {
    // Traditional for Taiwan/Hong Kong/Macau or an explicit -hant tag; else Simplified.
    return /\b(tw|hk|mo|hant)\b/.test(l) ? 'zh-Hant' : 'zh-Hans';
  }
  if (l.startsWith('ko')) return 'ko';
  if (l.startsWith('es')) return 'es';
  if (l.startsWith('fr')) return 'fr';
  if (l.startsWith('de')) return 'de';
  return 'en';
}
export function getLang() { return lang; }
export function setLang(l) { lang = MESSAGES[l] ? l : 'en'; }

export function t(key, params) {
  const table = MESSAGES[lang] || MESSAGES.en;
  let s = (key in table) ? table[key] : (MESSAGES.en[key] !== undefined ? MESSAGES.en[key] : key);
  if (params) for (const k in params) s = s.split('{' + k + '}').join(params[k]);
  return s;
}

// Apply translations to static markup: textContent for [data-i18n], title for [data-i18n-title].
export function applyStatic(root = document) {
  if (!root || !root.querySelectorAll) return;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.getAttribute('data-i18n-title')); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
}
