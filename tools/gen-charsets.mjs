#!/usr/bin/env node
// Generate docs/src/fontgen/charsets-data.js — the bulk character-set lists.
//
// Source of the lists: the per-character-set enable headers in the efont
// Arduino library (https://github.com/tanakamasayuki/efont), each a flat list
// of `#define __EFONT_ENABLE_0X3042__` lines. Those *lists* — which codepoints
// belong in an "ASCII" / "Japanese mini" / "CJK" set for an embedded display —
// are the reusable part and are what this generator lifts. The /efont/ Unicode
// font data that library ships is a separate work by its own authors and is
// NOT used here: this tool rasterizes whatever typeface the user picks.
//
// Nothing downstream is named after efont for that reason; the generated keys
// are plain set names.
//
// Output is a compact `START-END,...` hex range string per set, which the
// browser expands with parseRanges() (docs/src/fontgen/charsets.js).
//
//   node tools/gen-charsets.mjs          # fetch from GitHub, rewrite the module
//   node tools/gen-charsets.mjs --check  # exit 1 if the committed file is stale
//
// Curated sets the source lists do not cover (units/symbols, clock, ...) live
// in charsets.js by hand — this generator only owns the imported bulk.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'docs/src/fontgen/charsets-data.js');

const EFONT_REF = 'master';
const BASE = `https://raw.githubusercontent.com/tanakamasayuki/efont/${EFONT_REF}/src`;

// set id -> source header. Order is the order they appear in the module.
const SOURCES = [
  ['latin1', 'efontEnableAscii.h'],
  ['jaMini', 'efontEnableJaMini.h'],
  ['ja', 'efontEnableJa.h'],
  ['cjk', 'efontEnableCJK.h'],
  ['cn', 'efontEnableCn.h'],
  ['tw', 'efontEnableTw.h'],
  ['kr', 'efontEnableKr.h'],
];

// "__EFONT_ENABLE_0X3042__" -> 0x3042, deduped and sorted.
function codepoints(text) {
  const out = new Set();
  for (const m of text.matchAll(/__EFONT_ENABLE_0X([0-9A-Fa-f]+)__/g)) out.add(parseInt(m[1], 16));
  return [...out].sort((a, b) => a - b);
}

// [0x20,0x21,0x22,0x30] -> "20-22,30" (single codepoints stay bare).
function encodeRanges(cps) {
  const parts = [];
  let start = cps[0], prev = cps[0];
  for (const c of cps.slice(1)) {
    if (c === prev + 1) { prev = c; continue; }
    parts.push(start === prev ? start.toString(16).toUpperCase() : `${start.toString(16).toUpperCase()}-${prev.toString(16).toUpperCase()}`);
    start = prev = c;
  }
  parts.push(start === prev ? start.toString(16).toUpperCase() : `${start.toString(16).toUpperCase()}-${prev.toString(16).toUpperCase()}`);
  return parts.join(',');
}

async function build() {
  const entries = [];
  for (const [id, file] of SOURCES) {
    const res = await fetch(`${BASE}/${file}`);
    if (!res.ok) throw new Error(`fetch ${file}: HTTP ${res.status}`);
    const cps = codepoints(await res.text());
    if (!cps.length) throw new Error(`${file}: no __EFONT_ENABLE_0X…__ defines found`);
    entries.push({ id, file, count: cps.length, ranges: encodeRanges(cps) });
    console.error(`  ${id.padEnd(12)} ${String(cps.length).padStart(6)} chars  (${file})`);
  }

  let s = '';
  s += '// GENERATED by tools/gen-charsets.mjs. Do not edit by hand.\n';
  s += '// Character LISTS imported from the enable-headers of the efont Arduino\n';
  s += `// library (https://github.com/tanakamasayuki/efont @ ${EFONT_REF}, src/efontEnable*.h).\n`;
  s += '// Only the codepoint lists are used; the /efont/ Unicode font data itself is a\n';
  s += '// separate work by its own authors and is not part of this tool.\n';
  s += '// Each value is a compact "START-END,SINGLE,..." list of hex codepoints;\n';
  s += '// expand it with parseRanges() from ./charsets.js.\n';
  s += 'export const SET_RANGES = {\n';
  for (const e of entries) {
    s += `  // ${e.file} — ${e.count} characters\n`;
    s += `  ${e.id}: '${e.ranges}',\n`;
  }
  s += '};\n\n';
  s += 'export const SET_COUNTS = {\n';
  for (const e of entries) s += `  ${e.id}: ${e.count},\n`;
  s += '};\n';
  return s;
}

let text;
try {
  text = await build();
} catch (e) {
  // --check exists to catch the committed copy drifting from upstream, not to
  // make CI depend on GitHub being reachable. A fetch failure is reported and
  // skipped; a content difference still fails.
  if (process.argv.includes('--check')) {
    console.error(`SKIP: could not reach the source headers (${e.message}).`);
    process.exit(0);
  }
  throw e;
}
if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== text) {
    console.error(`\ncharsets-data.js is STALE — run: node tools/gen-charsets.mjs`);
    process.exit(1);
  }
  console.log('charsets-data.js is up to date.');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
