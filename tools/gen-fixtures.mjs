#!/usr/bin/env node
// Regenerate committed generated headers from stored project files (.lgfxsb.json)
// using the *production* codegen, so an output-format change (e.g. dropping
// `update`, adding a `Canvas` typedef) propagates with a single run instead of
// hand-editing every fixture/example header.
//
//   node tools/gen-fixtures.mjs --write    # (re)write headers in place
//   node tools/gen-fixtures.mjs --check    # exit 1 if any header is stale (CI/pre-commit guard)
//
// Source of truth: each fixture's `.lgfxsb.json` — the same save format the GUI
// authoring tool produces (persist.serialize). The `.ino` files are hand-written
// or hand-curated and call only the stable public API (begin / show / setProfile /
// setOverlay), so they survive output-format changes and are NOT generated here.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { generateHeader } from '../docs/src/codegen.js';
import { isProject } from '../docs/src/persist.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Fixtures whose MyScreen.h is generated from a stored project file.
// `headers` may list several outputs that share one source project (the header
// is framework-agnostic; only the hand-written .ino differs per framework).
const FIXTURES = [
  {
    name: 'examples',
    source: 'fixtures/sample.lgfxsb.json',
    headers: [
      'examples/BasicLovyanGFX/MyScreen.h',
      'examples/BasicM5Unified/MyScreen.h',
    ],
  },
  {
    name: 'codegen_roundtrip',
    source: 'tests/codegen_roundtrip/codegen_roundtrip.lgfxsb.json',
    headers: ['tests/codegen_roundtrip/MyScreen.h'],
    // The .h is gitignored and regenerated at pytest collection (via gen.mjs),
    // so it is not a committed golden: --write produces it, --check skips it
    // (it does not exist on a pristine checkout).
    committed: false,
  },
];

// Generated by hand ON PURPOSE — the current codegen cannot emit this shape yet
// (nested group structs like `s.header.title`). Listed here so it is never
// silently assumed to be auto-generated.
const HAND_WRITTEN = ['tests/build_lovyangfx/MyScreen.h'];

const norm = (s) => s.replace(/\r/g, '');

function loadProject(rel) {
  const obj = JSON.parse(readFileSync(join(root, rel), 'utf8'));
  if (!isProject(obj)) throw new Error(`${rel}: not a valid project file`);
  return obj;
}

/**
 * Regenerate fixture headers.
 * @param {'write'|'check'} mode
 * @param {string|null} only - if given, only the fixture with this `name`
 * @returns {{written: string[], stale: string[]}}
 */
export function regenerate(mode, only = null) {
  const written = [];
  const stale = [];
  const fixtures = only ? FIXTURES.filter((f) => f.name === only) : FIXTURES;
  for (const fx of fixtures) {
    // Non-committed headers (gitignored, regenerated at test time) are produced
    // by --write but skipped by --check (they are absent on a pristine checkout).
    if (mode === 'check' && fx.committed === false) continue;
    const header = generateHeader(loadProject(fx.source));
    const next = norm(header);
    for (const rel of fx.headers) {
      const path = join(root, rel);
      let cur = null;
      try { cur = norm(readFileSync(path, 'utf8')); } catch { /* missing → treat as stale */ }
      if (cur === next) continue;
      if (mode === 'write') { writeFileSync(path, header); written.push(rel); }
      else stale.push(rel);
    }
  }
  return { written, stale };
}

// CLI
if (import.meta.url === `file://${process.argv[1]}`) {
  const mode = process.argv.includes('--check') ? 'check'
    : process.argv.includes('--write') ? 'write' : null;
  if (!mode) {
    console.error('usage: node tools/gen-fixtures.mjs --write | --check');
    process.exit(2);
  }
  const { written, stale } = regenerate(mode);
  if (mode === 'check') {
    for (const rel of stale) console.error(`STALE: ${rel}`);
    if (stale.length) {
      console.error(`\n${stale.length} generated header(s) out of date — run: node tools/gen-fixtures.mjs --write`);
      process.exit(1);
    }
    console.log('all generated headers up to date.');
  } else {
    for (const rel of written) console.log(`written: ${rel}`);
    console.log(written.length ? `\n${written.length} header(s) regenerated.` : 'all headers already current.');
  }
  console.log(`hand-written (exempt): ${HAND_WRITTEN.join(', ')}`);
}
